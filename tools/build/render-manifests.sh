#!/usr/bin/env bash
# ==================================================================================================
#  render-manifests.sh - the plain Kubernetes manifests, generated from the Helm charts.
#
#      tools/build/render-manifests.sh           write apps/app/deploy-kubernetes/manifests/*.yaml
#      tools/build/render-manifests.sh --check   fail if what is committed differs from a fresh render
#
#  The manifests are GENERATED, like the data model in docs/architecture.html: change a chart or its
#  manifests/*.values.yaml, run this, commit both. Nobody edits manifests/*.yaml by hand - the
#  pipeline's chart:lint job runs --check and fails on any drift.
#
#  An edition whose chart is not in the tree is skipped: the public Community repository carries
#  proxyma-community and its manifest, not proxyma-enterprise.
#
#  Needs helm 3 on PATH, or HELM naming the binary. Nothing else, and no cluster: `helm template`
#  renders offline, which is also why the values files give the database password as a Secret the
#  operator creates - a password generated at render time would be a new one on every render.
# ==================================================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
K8S="$ROOT/apps/app/deploy-kubernetes"
HELM="${HELM:-helm}"
CHECK=0
case "${1:-}" in
    --check) CHECK=1 ;;
    "") ;;
    *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

command -v "$HELM" >/dev/null 2>&1 || { echo "[ERROR] helm not found - put it on PATH or set HELM" >&2; exit 1; }

OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT

FAILED=0
for edition in enterprise community; do
    chart="$K8S/charts/proxyma-$edition"
    if [ ! -f "$chart/Chart.yaml" ]; then
        echo "  charts/proxyma-$edition is not in this tree - skipped"
        continue
    fi
    # The library chart is a file:// dependency; this packages it into charts/ (gitignored).
    "$HELM" dependency build "$chart" >/dev/null
    {
        printf '# GENERATED by tools/build/render-manifests.sh from charts/proxyma-%s with\n' "$edition"
        printf '# manifests/%s.values.yaml. Do not edit - change the chart or the values and re-run it.\n' "$edition"
        printf '# Apply into a namespace of your own: kubectl apply -n <namespace> -f %s.yaml\n' "$edition"
        "$HELM" template proxyma "$chart" --skip-tests -f "$K8S/manifests/$edition.values.yaml"
    } | tr -d '\r' > "$OUT/$edition.yaml"

    target="$K8S/manifests/$edition.yaml"
    if [ "$CHECK" = 1 ]; then
        if ! cmp -s "$OUT/$edition.yaml" "$target"; then
            echo "[ERROR] manifests/$edition.yaml is out of date - run tools/build/render-manifests.sh and commit it" >&2
            diff -u "$target" "$OUT/$edition.yaml" | head -40 >&2 || true
            FAILED=1
        else
            echo "  manifests/$edition.yaml is current"
        fi
    else
        cp "$OUT/$edition.yaml" "$target"
        echo "  wrote manifests/$edition.yaml ($(grep -c '^kind:' "$target") resources)"
    fi
done
exit "$FAILED"
