/**
 * THE KIT REGISTRY - every component of libs/ui-kit/react/index.ts as DATA: what it is, when to
 * reach for it and when not, the props a page author sets, and the specimens the gallery draws.
 *
 * ONE SOURCE FOR TWO READERS. The gallery at /__kit (KitGallery.tsx) renders an entry's words
 * beside its specimens (kitSpecimens.tsx, keyed by the same name); the design guideline is
 * generated from this file and kitTokens.ts by a script that reads them with `node`. So this file
 * stays PLAIN .ts with no imports and no JSX - type stripping is all `node` needs.
 *
 * kitRegistry.test.ts (in test:checks) fails when a component exported by the kit has no entry
 * here, when an entry names something the kit does not export, and when an entry's specimens are
 * not in kitSpecimens.tsx. Adding a component to the kit means: an entry here, and a specimen.
 *
 * `props` documents what a page author sets; the full prop types are the source's (`file`), which
 * a generator can read with the TypeScript compiler.
 */

export type KitLevel = 'foundation' | 'L1' | 'L2' | 'L3'
export type KitAtomic = 'atom' | 'molecule' | 'organism' | 'template'
export type KitGroupId =
  | 'motion' | 'text' | 'controls' | 'marks' | 'meters' | 'brand' | 'surfaces' | 'states' | 'forms' | 'lists' | 'tables'
  | 'overlays' | 'menus' | 'chat' | 'sources' | 'chrome' | 'screens' | 'settings' | 'marketing'

export interface KitProp {
  name: string
  /** The prop's type, simplified to one line. */
  type: string
  default?: string
  required?: boolean
  note: string
}

export interface KitEntry {
  /** The export's name in libs/ui-kit/react/index.ts. */
  name: string
  /** Its source, relative to libs/ui-kit/react/ - where the full prop types are. */
  file: string
  level: KitLevel
  atomic: KitAtomic
  group: KitGroupId
  /** One sentence: what it is and is for. */
  purpose: string
  /** When to reach for it. */
  use: string[]
  /** When not to, and what to use instead. */
  avoid: string[]
  /** The props a page author sets, in the order they matter. */
  props: KitProp[]
  /** Other kit exports to know beside it. */
  related?: string[]
  /** The titles of its specimens in kitSpecimens.tsx, in order (an anchor `#Name-1`...). */
  specimens: string[]
}

