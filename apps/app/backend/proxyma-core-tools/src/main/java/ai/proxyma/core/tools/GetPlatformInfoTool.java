package ai.proxyma.core.tools;

import ai.proxyma.core.settings.config.ProductIdentity;
import ai.proxyma.core.system.util.SystemInfo;
import ai.proxyma.core.tools.schema.ToolFieldType;
import ai.proxyma.core.tools.schema.ToolResult;
import ai.proxyma.core.tools.schema.ToolResultField;

import org.springframework.ai.tool.annotation.Tool;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.info.BuildProperties;
import org.springframework.stereotype.Component;

import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;

// BuildProperties is only auto-configured by Spring Boot when META-INF/build-info.properties is
// present on the classpath (generated by the spring-boot-maven-plugin's build-info goal, bound to
// both proxyma-desktop's and proxyma-server's repackage execution) - absent in a plain `mvn
// compile`/IDE run, so this is injected as Optional rather than a hard dependency to avoid an
// unresolvable-bean startup failure in that case.
@Component
public class GetPlatformInfoTool {

    private final ProductIdentity productIdentity;
    private final SystemInfo systemInfo;
    private final Optional<BuildProperties> buildProperties;
    private final String version;
    private final boolean multiUser;
    // The home server is the desktop application in a container (single user, multiUser false),
    // so without this it reported "desktop" - and the agent then described a folder picker and a
    // local filesystem the home server does not have. Same property ConfigController reads.
    private final boolean homeServer;

    public GetPlatformInfoTool(ProductIdentity productIdentity, SystemInfo systemInfo,
            Optional<BuildProperties> buildProperties,
            @Value("${spring.application.version:0.0.0}") String version,
            @Value("${proxyma.multi-user:false}") boolean multiUser,
            @Value("${proxyma.home-server:false}") boolean homeServer) {
        this.productIdentity = productIdentity;
        this.systemInfo = systemInfo;
        this.buildProperties = buildProperties;
        this.version = version;
        this.multiUser = multiUser;
        this.homeServer = homeServer;
    }

    @Tool(description = "This product's name, version, deployment mode (desktop/home-server/server), host OS and build "
            + "date if known. Use for questions about the product, its version or build; never guess these.")
    @ToolResult(
            value = {
                @ToolResultField(name = "name", type = ToolFieldType.STRING, always = true,
                        description = "Product name."),
                @ToolResultField(name = "version", type = ToolFieldType.STRING, always = true,
                        description = "Running version."),
                @ToolResultField(name = "mode", type = ToolFieldType.STRING, always = true,
                        description = "Deployment mode: 'desktop', 'home-server' or 'server'."),
                @ToolResultField(name = "operatingSystem", type = ToolFieldType.STRING, always = true,
                        description = "Host OS: 'windows', 'macos' or 'linux'."),
                @ToolResultField(name = "buildDate", type = ToolFieldType.STRING, always = true,
                        description = "Build timestamp, or a placeholder when the build did not stamp one.")
            },
            envelope = false,
            description = "Identity and build of this installation. Reports no success flag: every value is "
                    + "read locally.")
    public Map<String, Object> getPlatformInfo() {
        Map<String, Object> result = new LinkedHashMap<>();
        result.put("name", productIdentity.getProductName());
        result.put("version", version);
        result.put("mode", multiUser ? "server" : homeServer ? "home-server" : "desktop");
        result.put("operatingSystem", systemInfo.isWindows() ? "windows" : systemInfo.isMac() ? "macos" : "linux");
        result.put("buildDate", buildProperties
                .map(bp -> DateTimeFormatter.ISO_LOCAL_DATE.withZone(ZoneId.systemDefault()).format(bp.getTime()))
                .orElse("unknown - this build has no recorded build timestamp"));
        return result;
    }
}
