package ai.proxyma.it.harness;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.time.Duration;
import java.util.ArrayList;
import java.util.Base64;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * The two back-office services - license issuance and telemetry ingest - booted the same way the
 * product is.
 *
 * <p>Kept apart from {@link ProxymaApp} because they are a different kind of thing: Spring MVC
 * rather than WebFlux, no SPA to serve from the jar, no model provider, and an administrator
 * rather than an end user. What they share is the shape of every journey against them - create the
 * first admin through the setup endpoint, sign in, then use the API - so that shape lives here.
 *
 * <h2>Both need PostgreSQL, whatever the license service's own defaults say</h2>
 *
 * Telemetry is explicit about it: the driver is hardcoded and {@code PROXYMA_TELEMETRY_DB_URL} has
 * no default at all.
 *
 * <p>The license service LOOKS like it does not. Its {@code application.yml} defaults to
 * {@code jdbc:h2:file:/data/license} with {@code org.h2.Driver}, which reads as a zero-dependency
 * fallback. <b>It is dead configuration.</b> The first draft of this harness took it at face value
 * and the jar refused to start: {@code Cannot load driver class: org.h2.Driver}. The pom declares
 * only {@code org.postgresql:postgresql} at runtime scope and the packaged jar carries exactly one
 * driver - there is no H2 anywhere in it. The deployment agrees: {@code docker-compose.yml} marks
 * {@code PROXYMA_LICENSE_DB_URL} required with {@code :?...is required} and pins the driver to
 * PostgreSQL, so nothing real has ever taken that branch.
 *
 * <p>Recorded here rather than worked around silently, because the default is the misleading kind:
 * it does not warn, it does not degrade, it fails at startup on the one path a newcomer would try
 * first.
 */
public final class ServiceApp implements AutoCloseable {

    private final Env.App app;
    private final ManagedProcess process;
    private final Http api;
    private final Path dataDir;
    private final int port;

    private ServiceApp(Env.App app, ManagedProcess process, Http api, Path dataDir, int port) {
        this.app = app;
        this.process = process;
        this.api = api;
        this.dataDir = dataDir;
        this.port = port;
    }

    public Http api() { return api; }

    /**
     * The PEM this license service signs with, as its public half.
     *
     * <p>Read by {@link ProxymaApp#bootServer} to tell the instance under test which issuer to
     * trust - see the comment there for why shadowing a classpath resource is the only way to
     * say that to a build.
     */
    public Path publicKeyPem() { return dataDir.resolve("keys/license-public.pem"); }
    public Path dataDir() { return dataDir; }
    public String baseUrl() { return "http://127.0.0.1:" + port; }
    public ManagedProcess process() { return process; }
    public Http newClient() { return new Http(baseUrl()); }

    private static final Map<Env.App, ServiceApp> SHARED = new ConcurrentHashMap<>();

    /** One instance per service for the whole suite - see {@link ProxymaApp#shared}. */
    public static ServiceApp shared(Env.App which) {
        return SHARED.computeIfAbsent(which, w -> {
            ServiceApp service = w == Env.App.LICENSE ? bootLicense() : bootTelemetry();
            Runtime.getRuntime().addShutdownHook(new Thread(service::close));
            return service;
        });
    }

    /**
     * The license service against a PostgreSQL container, with a freshly generated signing key
     * pair.
     *
     * <p>The keys are generated per run and thrown away with the scratch directory. That is not
     * only hygiene: the real signing key is the one that signs every license ever issued, it lives
     * on the production host at mode 600, and it is never generated by anything that also runs a
     * build. A suite that borrowed it could mint licenses.
     */
    public static ServiceApp bootLicense() {
        Path jar = Env.requireJar(Env.App.LICENSE);
        var postgres = Stores.postgres();
        Path data = Env.scratch("license");
        Path keys = data.resolve("keys");
        mkdirs(keys);
        writeKeyPair(keys, "license-private.pem", "license-public.pem");

        Map<String, String> env = new LinkedHashMap<>(baseEnvironment(data));
        // Every one of these four, not just the URL. The driver and the dialect have their own
        // defaults pointing at H2, so setting the URL alone leaves Hibernate speaking H2 to a
        // PostgreSQL socket - see this class's comment on why the H2 defaults are unreachable.
        env.put("PROXYMA_LICENSE_DB_URL", postgres.getJdbcUrl());
        env.put("PROXYMA_LICENSE_DB_DRIVER", "org.postgresql.Driver");
        env.put("PROXYMA_LICENSE_DB_USER", postgres.getUsername());
        env.put("PROXYMA_LICENSE_DB_PASSWORD", postgres.getPassword());
        env.put("PROXYMA_LICENSE_DB_PLATFORM", "org.hibernate.dialect.PostgreSQLDialect");
        env.put("PROXYMA_LICENSE_DATA_DIR", data.toString());
        env.put("PROXYMA_LICENSE_SIGNING_PRIVATE_KEY_FILE", keys.resolve("license-private.pem").toString());
        env.put("PROXYMA_LICENSE_SIGNING_PUBLIC_KEY_FILE", keys.resolve("license-public.pem").toString());
        // A known secret, so a journey can sign a webhook the way Lemon Squeezy does. Without one
        // the webhook endpoint rejects everything, which is correct and untestable.
        env.put("LEMONSQUEEZY_WEBHOOK_SECRET", WEBHOOK_SECRET);

        return boot(Env.App.LICENSE, jar, data, env, "PROXYMA_LICENSE_PORT");
    }

    /** The webhook secret the license service is booted with, for signing a test purchase. */
    public static final String WEBHOOK_SECRET = "proxyma-it-webhook-secret";

    /** The telemetry service against a PostgreSQL container. */
    public static ServiceApp bootTelemetry() {
        Path jar = Env.requireJar(Env.App.TELEMETRY);
        var postgres = Stores.postgres();
        Path data = Env.scratch("telemetry");
        mkdirs(data);

        Map<String, String> env = new LinkedHashMap<>(baseEnvironment(data));
        env.put("PROXYMA_TELEMETRY_DB_URL", postgres.getJdbcUrl());
        env.put("PROXYMA_TELEMETRY_DB_USER", postgres.getUsername());
        env.put("PROXYMA_TELEMETRY_DB_PASSWORD", postgres.getPassword());
        env.put("PROXYMA_TELEMETRY_DATA_DIR", data.toString());

        return boot(Env.App.TELEMETRY, jar, data, env, "PROXYMA_TELEMETRY_PORT");
    }

    private static ServiceApp boot(Env.App which, Path jar, Path data,
                                   Map<String, String> env, String portVariable) {
        int port = ProxymaApp.freePort();
        env.put(portVariable, String.valueOf(port));

        List<String> command = new ArrayList<>(List.of(
                Env.java(), "-Dspring.main.banner-mode=off", "-Dserver.port=" + port,
                "-jar", jar.toString()));

        ManagedProcess process = ManagedProcess.start(
                which.name().toLowerCase(java.util.Locale.ROOT), command, data, env);
        Http api = new Http("http://127.0.0.1:" + port);
        try {
            // /api/v1/setup/status is the one endpoint both services answer before anything has
            // been configured, which makes it the only honest readiness probe: a health endpoint
            // that answered while the schema was still being created would let a test start
            // issuing licenses into a half-built database.
            process.awaitReady("HTTP on port " + port,
                    () -> api.get("/api/v1/setup/status").status() == 200, Duration.ofMinutes(2));
        } catch (RuntimeException e) {
            process.stop();
            throw e;
        }
        return new ServiceApp(which, process, api, data, port);
    }

    private static Map<String, String> baseEnvironment(Path data) {
        Map<String, String> env = new LinkedHashMap<>();
        // Both services default every path to /data, which is a container path that on a
        // developer machine is either absent or unwritable.
        env.put("HOME", data.toString());
        env.put("USERPROFILE", data.toString());
        env.put("LOCALAPPDATA", data.toString());
        env.put("XDG_DATA_HOME", data.toString());
        return env;
    }

    // -- The setup-then-sign-in shape both services share ----------------------

    /**
     * Creates the first administrator if there is not one yet, signs in, and returns a client
     * carrying the admin token.
     *
     * <p>{@code POST /api/v1/setup} is unauthenticated BY NECESSITY - there is nobody to
     * authenticate as before it runs - so it closes itself after the first call, and on telemetry
     * it also wants the setup token only the host's disk holds. That is the security model of a
     * fresh install, and it is why the journeys assert a second call is refused rather than merely
     * that the first one worked.
     */
    public Http signInAsAdmin(String username, String password) {
        // "needed", not "completed" - the flag says whether setup still HAS to run, so a fresh
        // install answers true. Reading it the other way round would skip setup on a fresh
        // instance and then fail at the login with an unhelpful 401.
        if (api.get("/api/v1/setup/status").ok().json().path("needed").asBoolean(false)) {
            Map<String, String> body = new LinkedHashMap<>(Map.of("username", username, "password", password));
            // The telemetry service takes setup only with the one-time token it writes into its data
            // directory (2026-10-14) - what install.sh prints for an operator. A service that writes
            // none ignores the field.
            Path token = dataDir.resolve("setup-token");
            if (Files.exists(token)) {
                try {
                    body.put("setupToken", Files.readString(token).strip());
                } catch (IOException e) {
                    throw new UncheckedIOException(e);
                }
            }
            api.post("/api/v1/setup", body).ok();
        }
        String token = api.post("/api/v1/admin/login",
                Map.of("username", username, "password", password)).ok().text("/token");
        if (token.isBlank()) {
            throw new AssertionError("admin login returned no token for " + app);
        }
        return newClient().bearer(token);
    }

    /** Same two PEM encodings the deploy scripts write with openssl. */
    private static void writeKeyPair(Path dir, String privateName, String publicName) {
        try {
            KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
            generator.initialize(2048);
            KeyPair pair = generator.generateKeyPair();
            Files.writeString(dir.resolve(privateName),
                    pem("PRIVATE KEY", pair.getPrivate().getEncoded()), StandardCharsets.UTF_8);
            Files.writeString(dir.resolve(publicName),
                    pem("PUBLIC KEY", pair.getPublic().getEncoded()), StandardCharsets.UTF_8);
        } catch (Exception e) {
            throw new IllegalStateException("could not write a signing key pair into " + dir, e);
        }
    }

    private static String pem(String label, byte[] der) {
        String body = Base64.getMimeEncoder(64, "\n".getBytes(StandardCharsets.UTF_8)).encodeToString(der);
        return "-----BEGIN " + label + "-----\n" + body + "\n-----END " + label + "-----\n";
    }

    private static void mkdirs(Path... dirs) {
        for (Path dir : dirs) {
            try {
                Files.createDirectories(dir);
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }
    }

    @Override
    public void close() { process.stop(); }
}
